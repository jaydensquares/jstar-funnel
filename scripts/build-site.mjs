export function visual(v, eager = false) {
  if (!v) return '';
  if (v.type === 'phone-video') return `<div class="phone${v.ratio === '916' ? ' r916' : ''}"><video data-src="${v.src}" poster="${v.poster}" muted loop playsinline preload="none" aria-label="Screen recording of the JStar Pro app"></video></div>`;
  if (v.type === 'phone-img') return `<div class="phone"><img src="${v.src}" alt="${esc(v.alt)}" ${eager ? '' : 'loading="lazy"'}></div>`;
  if (v.type === 'browser') return `<div class="browser"><div class="bar"><i></i><i></i><i></i><span>getjstarpro.com/app</span></div><img src="${v.src}" alt="${esc(v.alt)}" width="2560" height="1600" ${eager ? '' : 'loading="lazy"'}></div>`;
  if (v.type === 'shot') return `<div class="shot${v.wide ? ' wide' : ''}"><img class="ui" src="${v.src}" alt="${esc(v.alt)}" ${eager ? '' : 'loading="lazy"'}></div>`;
  if (v.type === 'vsl') return `<div class="vsl" id="vsl-${path.basename(v.src, '.mp4')}" data-vsl="${v.src}" data-poster="${v.poster}"><img src="${v.poster}" alt="" width="1280" height="720" ${eager ? '' : 'loading="lazy"'}><button class="play" type="button" aria-label="Play: ${esc(v.cap)}"><span class="cap"><b>${esc(v.cap)}</b><span>${esc(v.sub || '')}</span></span><span class="pb">${ICON.play}</span></button></div>`;
  return '';
}

